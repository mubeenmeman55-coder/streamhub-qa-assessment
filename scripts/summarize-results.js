// Builds RESULTS.md from the committed Cucumber JSON reports, the SQL output and the self-healing report,
// so the numbers in the document are never typed by hand.   npm run results
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const rel = (p) => p.split(path.sep).join('/');
const readJson = (f) => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));

function summarise(reportFile) {
  const features = readJson(reportFile);
  const perFeature = [];
  const failures = [];
  const total = { scenarios: 0, passed: 0, failed: 0, steps: 0 };
  for (const f of features) {
    const row = { name: f.name, uri: rel(f.uri), scenarios: 0, passed: 0, failed: 0 };
    for (const sc of f.elements.filter((e) => e.type === 'scenario')) {
      const steps = sc.steps.filter((s) => s.hidden !== true);
      const bad = steps.find((s) => s.result.status !== 'passed');
      row.scenarios += 1;
      total.steps += steps.length;
      if (bad) { row.failed += 1; failures.push({ feature: f.name, scenario: sc.name, step: bad.name, error: (bad.result.error_message || bad.result.status).split('\n')[0].slice(0, 140) }); }
      else row.passed += 1;
    }
    total.scenarios += row.scenarios; total.passed += row.passed; total.failed += row.failed;
    perFeature.push(row);
  }
  return { total, perFeature, failures };
}

const suites = [
  ['A2 - EMI web app (UI)', 'reports/cucumber/webapp.json', 'must pass'],
  ['A3 - JSONPlaceholder POST /posts', 'reports/cucumber/jsonplaceholder.json', 'must pass'],
  ['A3 strict - local validating posts API', 'reports/cucumber/validating-posts.json', 'must pass'],
  ['Optional extra - mock catalogue API', 'reports/cucumber/api.json', 'must pass'],
  ['A3 known gaps (strict 4xx expectation)', 'reports/cucumber/known-gap.json', 'fails by design'],
  ['Self-healing demo (broken locators)', 'reports/cucumber/broken.json', 'fails by design'],
];

const out = [];
out.push('# Test execution results', '', '_Generated by `npm run results` from the committed reports in `reports/`. Re-run the suites, then this script, to refresh._', '');
out.push('## Summary', '', '| Suite | Scenarios | Passed | Failed | Expected |', '|---|---:|---:|---:|---|');
const details = [];
for (const [label, file, expectation] of suites) {
  if (!fs.existsSync(path.join(root, file))) continue;
  const s = summarise(file);
  out.push(`| ${label} | ${s.total.scenarios} | ${s.total.passed} | ${s.total.failed} | ${expectation} |`);
  details.push({ label, file, expectation, ...s });
}
const all = fs.existsSync(path.join(root, 'reports/cucumber/all.json')) ? summarise('reports/cucumber/all.json') : null;
if (all) out.push(`| **Full run (\`npm test\`)** | **${all.total.scenarios}** | **${all.total.passed}** | **${all.total.failed}** | must pass |`);
out.push('', 'Failures in the last two suites are intentional: they document a third-party API that does not validate input and demonstrate broken locators for the self-healing exercise.', '');

out.push('## Per feature file', '');
for (const d of details) {
  out.push(`### ${d.label}`, '', `Report: \`${d.file.replace('.json', '.html')}\``, '', '| Feature | Scenarios | Passed | Failed |', '|---|---:|---:|---:|');
  for (const f of d.perFeature) out.push(`| ${f.name} (\`${f.uri}\`) | ${f.scenarios} | ${f.passed} | ${f.failed} |`);
  out.push('');
}

out.push('## Intentional failures (evidence)', '');
for (const d of details.filter((x) => x.expectation === 'fails by design')) {
  out.push(`**${d.label}**`, '', '| Scenario | Failing step | Reason |', '|---|---|---|');
  for (const f of d.failures) out.push(`| ${f.scenario} | ${f.step} | ${f.error.replace(/\|/g, '\\|')} |`);
  out.push('');
}

// SQL
out.push('## A4 - SQL query outputs', '', 'Schema, sample data, query and result are in `sql/`; the images below are generated by `npm run sql`.', '');
for (const [n, title] of [['scenario1', 'Scenario 1 - round-trip transfers (within 10% and 24 hours)'], ['scenario2', 'Scenario 2 - IPL 2024 players with 30+ runs in 3+ consecutive matches']]) {
  out.push(`### ${title}`, '', `![${title} - schema and data](reports/sql/${n}-schema-and-data.png)`, '', `![${title} - output](reports/sql/${n}-output.png)`, '');
}

// Self-healing
const heal = path.join(root, 'reports/self-healing/healing-report.json');
if (fs.existsSync(heal)) {
  const h = JSON.parse(fs.readFileSync(heal, 'utf8'));
  out.push('## Self-healing proof of concept', '', `Mode: **${h.mode}**`, '', '| Locator | Broken selector | Healed (validated in a browser) |', '|---|---|---|');
  for (const r of h.results) out.push(`| ${r.key} | \`${r.brokenSelector}\` | ${r.suggested ? `\`${r.suggested}\`` : r.outcome} |`);
  out.push('');
}

// Screenshots
const shotsDir = path.join(root, 'reports/screenshots');
if (fs.existsSync(shotsDir)) {
  const shots = fs.readdirSync(shotsDir).filter((f) => f.endsWith('.png')).sort();
  out.push('## UI screenshots', '', `${shots.length} screenshots (one per UI scenario) are in \`reports/screenshots/\`. A few examples:`, '');
  for (const pick of [/^Calculated_figures_match_my_independent_calculation_25_00_000/, /^Charts_are_visible/, /^Report_view_lists/, /^Comparing_two_loans/, /^Eligibility___?an_EMI|^Eligibility/]) {
    const f = shots.find((s) => pick.test(s));
    if (f) out.push(`**${f.replace(/\.png$/, '').replace(/_/g, ' ')}**`, '', `![${f}](reports/screenshots/${f})`, '');
  }
}

fs.writeFileSync(path.join(root, 'RESULTS.md'), out.join('\n') + '\n');
console.log(`RESULTS.md written (${details.length} suites)`);
